#!/usr/bin/env python3
"""Собрать transcript.txt длинной встречи (60+ минут) из блоков — детерминированно.

Запуск: python3 tests/evals/08-long-meeting/generate.py  (перезаписывает transcript.txt рядом).
Несущие события стоят на заданных минутах; между ними — рутинные блоки статуса по модулям.
Таймкод каждой реплики считается из длины предыдущей, поэтому повторный запуск даёт тот же файл.
После изменения генератора нужно обновить опорные цитаты, таймкоды и source_sha256 в core.json.
"""

from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent

MODULES = [
    "Закупки", "Склад", "Продажи", "Касса", "Отчётность", "Мастер-данные", "Права доступа", "Миграция остатков",
    "Ценообразование", "Возвраты", "Логистика", "Казначейство", "Маркировка", "Претензии", "Документооборот",
    "Бюджетирование", "Сервисные заявки", "Акции", "Поставщики", "Инвентаризация",
]
NEEDS = [
    "скорость оформления документов", "корректные остатки на утро", "понятные печатные формы",
    "закрытие смены без ручных правок", "сверка с бухгалтерией без расхождений", "единый справочник контрагентов",
    "чтобы кладовщики не вводили одно и то же дважды", "прозрачная история изменений цены",
]
WAITING = [
    "выгрузку справочников", "подтверждение формата файлов", "доступ к копии базы", "ответ по печатным формам",
    "примеры реальных документов", "список пользователей по ролям",
]
OWNERS = ["вашей ИТ-службы", "вашей бухгалтерии", "склада", "коммерческого отдела"]

INTRO = [
    ("Speaker 1", "Добрый день. Марк Белоусов, директор по ИТ «Озёрного Края». Это еженедельный штаб по внедрению учётной системы, у нас час с небольшим."),
    ("Speaker 2", "Добрый день. Алина Ржевская, «Белый Клён Софт», руководитель проекта. Со мной Степан Ковалёв, ведущий тестировщик."),
    ("Speaker 3", "Добрый день."),
    ("Speaker 4", "Добрый день, Жанна Острова, финансы, я от бизнеса."),
    ("Speaker 1", "Повестка как обычно: статус по модулям, тестирование, риски, план на следующие недели."),
]
EARLY_COMMITMENT = [
    ("Speaker 1", "Начнём с тестирования. Степан, что с нагрузочным тестированием?"),
    ("Speaker 3", "Стенд собран, сценарии готовы. Отчёт по нагрузочному тестированию пришлю до второго декабря."),
    ("Speaker 1", "Хорошо, второе декабря."),
]
RISK = [
    ("Speaker 2", "Теперь важное. Интеграция с банком: тестовый контур нам до сих пор не открыли."),
    ("Speaker 2", "Если банк не откроет доступ к тестовому контуру до десятого декабря, интеграция с банком сдвинется на две недели."),
    ("Speaker 4", "Две недели — это уже после закрытия года, для финансов это плохо."),
    ("Speaker 1", "Этот риск беру на себя, у меня есть контакт в банке, на этой неделе с ними поговорю."),
]
OPEN_PROPOSAL = [
    ("Speaker 4", "Может, отключим старую систему сразу в январе, без параллельной работы?"),
    ("Speaker 1", "Давайте вернёмся к отчётности, там больше вопросов."),
]
TRAINING = [
    ("Speaker 2", "По обучению пользователей предлагаем три волны: первая с первого декабря, затем склад и касса."),
    ("Speaker 4", "Три волны нас устраивают, только первую волну — с финансов."),
    ("Speaker 1", "Согласен: обучение в три волны, первая с первого декабря, начинаем с финансов."),
]
REVISION = [
    ("Speaker 3", "Вернусь к нагрузочному тестированию. Стенд переносят в другой дата-центр, второе декабря не успеваем."),
    ("Speaker 3", "Отчёт по нагрузочному тестированию пришлю до девятого декабря."),
    ("Speaker 1", "Хорошо, тогда девятое декабря вместо второго."),
]
CLOSING = [
    ("Speaker 2", "С нашей стороны: обновлённый план-график проекта пришлю до двадцать восьмого ноября."),
    ("Speaker 1", "Подведу итог: план-график — до двадцать восьмого ноября, отчёт по нагрузке — до девятого декабря, обучение — три волны с первого декабря, риск по банку — на мне."),
    ("Speaker 4", "И вопрос с отключением старой системы остаётся, его не решили."),
    ("Speaker 1", "Да, он открыт, вернёмся к нему на следующем штабе. Спасибо всем."),
    ("Speaker 2", "Спасибо, до следующей недели."),
]


def filler_block(index: int) -> list[tuple[str, str]]:
    module = MODULES[index % len(MODULES)]
    done = 10 + (index * 7) % 15
    total = done + 3 + index % 5
    left = total - done
    need = NEEDS[index % len(NEEDS)]
    waiting = WAITING[index % len(WAITING)]
    owner = OWNERS[index % len(OWNERS)]
    return [
        ("Speaker 2", f"По модулю «{module}»: закрыто {done} задач из {total}, в работе {left}."),
        ("Speaker 1", f"Что мешает закрыть оставшиеся {left}?"),
        ("Speaker 3", f"По «{module}» блокеров нет, ждём {waiting} от {owner}."),
        ("Speaker 4", f"Для бизнеса по «{module}» главное — {need}."),
        ("Speaker 2", "Учтём, это попадёт в план следующей недели."),
        ("Speaker 1", "Хорошо, дальше."),
    ]


def duration(text: str) -> int:
    return 7 + len(text) // 9


def stamp(seconds: int) -> str:
    return f"{seconds // 3600:02d}:{seconds % 3600 // 60:02d}:{seconds % 60:02d}"


def build() -> str:
    plan = [(0, INTRO), (150, EARLY_COMMITMENT), (31 * 60, RISK), (45 * 60, OPEN_PROPOSAL), (52 * 60, TRAINING), (58 * 60, REVISION), (63 * 60, CLOSING)]
    lines: list[str] = []
    clock = 5
    block = 0
    for target, event in plan:
        while clock < target:
            for speaker, text in filler_block(block):
                lines.append(f"[{stamp(clock)}] {speaker}: {text}")
                clock += duration(text)
            block += 1
        for speaker, text in event:
            lines.append(f"[{stamp(clock)}] {speaker}: {text}")
            clock += duration(text)
    return "\n".join(lines) + "\n"


def main() -> None:
    text = build()
    (HERE / "transcript.txt").write_text(text, encoding="utf-8")
    last = text.strip().splitlines()[-1][1:9]
    print(f"transcript.txt: {len(text)} знаков, {len(text.splitlines())} реплик, последняя в {last}")


if __name__ == "__main__":
    main()
